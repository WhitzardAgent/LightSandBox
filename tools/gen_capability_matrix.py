#!/usr/bin/env python3
"""Generate docs/reference/capability-matrix.md from the capability sources.

Sources, all parsed/loaded (no prose copies to rot):
* contracts/v1/sandbox-requirements.schema.json — frozen requirement
  dimensions and resource observation fields.
* contracts/v1/resolution-rules.json — requirement -> capability mapping,
  rejection codes, single-ID compatibility policy.
* crates/ls-core/src/domain/backend.rs — backend kinds, AUTO selection
  order, and the requirement dimension registry (parsed from Rust source).
* specs/host-profiles.json — host profile tiers and the measured
  portable-rootless summary.

Regeneration is byte-exact. `--check` compares without writing and fails
(exit 1, with a diff) on drift. Any broken parse expectation aborts loudly.
Stdlib only.

Exit codes: 0 written/verified, 1 drift/missing/parse failure, 2 usage.
"""
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / 'contracts' / 'v1' / 'sandbox-requirements.schema.json'
RULES = ROOT / 'contracts' / 'v1' / 'resolution-rules.json'
BACKEND_RS = ROOT / 'crates' / 'ls-core' / 'src' / 'domain' / 'backend.rs'
PROFILES = ROOT / 'specs' / 'host-profiles.json'
OUTPUT = ROOT / 'docs' / 'reference' / 'capability-matrix.md'


def fail(msg):
    raise SystemExit(f'gen_capability_matrix: parse/source failure: {msg}')


def parse_contracts():
    schema = json.loads(SCHEMA.read_text(encoding='utf-8'))
    rules = json.loads(RULES.read_text(encoding='utf-8'))
    try:
        dims = list(schema['properties']['requires']['properties'])
        resources = list(schema['properties']['resources']['properties'])
        mapping = rules['requirements_map']
        rejection = (rules['rejection']['code'], int(rules['rejection']['http_status']))
        policy = rules['single_id_compat']
    except (KeyError, TypeError, ValueError) as exc:
        fail(f'contract shape changed: {exc}')
    if set(dims) != set(mapping):
        fail(f'requirement dimensions {sorted(dims)} != requirements_map {sorted(mapping)}')
    if policy.get('default') != 'STRICT':
        fail(f'single_id_compatibility_policy default changed: {policy.get("default")!r}')
    rows = []
    for dim in dims:
        entry = mapping[dim]
        rows.append((dim, entry['capability'], entry['accepted_value']))
    return dims, resources, rows, rejection, policy


def parse_backend_rs():
    source = BACKEND_RS.read_text(encoding='utf-8')
    enum = re.search(r'pub enum BackendKind \{(.*?)\}', source, re.S)
    if not enum:
        fail('BackendKind enum not found in backend.rs')
    kinds = re.findall(r'^\s*([A-Z]\w+),?\s*$', enum.group(1), re.M)
    order_match = re.search(r'AUTO_ORDER:\s*\[BackendKind;\s*\d+\]\s*=\s*\[(.*?)\]', source, re.S)
    if not order_match:
        fail('BackendKind::AUTO_ORDER not found in backend.rs')
    order = re.findall(r'BackendKind::(\w+)', order_match.group(1))
    if not order or order[0] != 'Native':
        fail(f'unexpected AUTO order {order}; ADR 0002 requires Native first')
    if not set(order) <= set(kinds) or not set(kinds) - set(order):
        fail('AUTO order must be a strict subset of BackendKind variants (deferred kinds exist)')
    registry = dict(re.findall(r'pub const (\w+): &str = "([a-z_]+)";', source))
    all_match = re.search(r'pub const ALL: \[&str; \d+\] = \[(.*?)\]', source, re.S)
    if not registry or not all_match:
        fail('dimension registry (dim::*) not parseable from backend.rs')
    listed = re.findall(r'\b([A-Z_]{3,})\b', all_match.group(1))
    registry_dims = sorted(registry[name] for name in listed if name in registry)
    return [k.upper() for k in kinds], [k.upper() for k in order], registry_dims


def parse_profiles():
    data = json.loads(PROFILES.read_text(encoding='utf-8'))
    profiles = data.get('profiles')
    if not isinstance(profiles, list) or not profiles:
        fail('host-profiles.json lost the profiles list')
    observed = [p for p in profiles if p.get('observed')]
    if len(observed) != 1 or 'capabilities_summary' not in observed[0]:
        fail('expected exactly one observed host profile with a capabilities_summary')
    return data, profiles, observed[0]


def render(data):
    dims, resources, rows, rejection, policy = data['contracts']
    kinds, order, registry_dims = data['backend']
    meta, profiles, observed = data['profiles']
    extra = sorted(set(registry_dims) - set(dims))
    lines = [
        '<!-- GENERATED by tools/gen_capability_matrix.py. Do not edit by hand: change',
        '     the sources (contracts/v1, crates/ls-core, specs/host-profiles.json) and',
        '     regenerate. Drift is checked by `dev/check docs`. -->',
        '',
        '# Capability matrix',
        '',
    ]
    if extra:
        lines += [
            '> Registry note: the backend planner in code already names additional',
            '> requirement dimension(s): ' + ', '.join(f'`{d}`' for d in extra) + '.',
            '> These are not part of the frozen v1 requirement surface below; they are',
            '> reserved for the planned contract evolution and are not usable in v1',
            '> requests.',
            '',
        ]
    lines += [
        'Requirement dimensions are **hard preconditions**, not preferences: a `true`',
        f'requirement whose mapped host capability does not hold its accepted value sees',
        f'the request rejected before create with `{rejection[0]}` (HTTP {rejection[1]}).',
        '',
        '## Requirement dimensions (frozen v1 contract)',
        '',
        '| `requires.*` dimension | Host capability | Accepted value |',
        '|---|---|---|',
    ]
    for dim, capability, accepted in rows:
        lines.append(f'| `{dim}` | `{capability}` | `{accepted}` |')
    lines += [
        '',
        f'Source: `contracts/v1/resolution-rules.json` (`requirements_map`). Every declared',
        'dimension must appear in the effective capabilities even when unsupported — an',
        'unsupported dimension never silently disappears.',
        '',
        '## Resource observation fields (requests, not hard limits)',
        '',
        'The `resources.*` fields are observations/requests in canonical integer units.',
        'Hardness comes only from `requires.*`, never from setting a number:',
        '',
        '| Field | Unit |',
        '|---|---|',
        '| `memory_bytes` | bytes |',
        '| `storage_bytes` | bytes |',
        '| `cpu_millis` | milli-CPU |',
        '| `pids` | process ids |',
        '',
    ]
    if [r for r in rows] and sorted(resources) != ['cpu_millis', 'memory_bytes', 'pids', 'storage_bytes']:
        fail(f'resource fields changed: {resources}')
    lines += [
        'Source: `contracts/v1/sandbox-requirements.schema.json`.',
        '',
        '## Single-ID compatibility policy',
        '',
        '| Policy field | Default | Values |',
        '|---|---|---|',
        f"| `{policy['field']}` | `{policy['default']}` | "
        + ', '.join(f'`{v}`' for v in policy['values']) + ' |',
        '',
        'STRICT rejects unfaithful UID/GID expressions (image user other than uid 0,',
        'required ownership) at create/preflight; FLATTEN_ROOT is an explicit benchmark',
        'compatibility mode whose effects must be disclosed as degradations. The policy',
        'never downgrades an explicit `true` requirement from the map above.',
        '',
        '## Backend AUTO selection order',
        '',
        'Backends are selected by requirement satisfaction, never by binary name. Under',
        '`auto`, the first available backend in this order that observes SUPPORTED for',
        'every hard requirement wins:',
        '',
    ]
    for i, kind in enumerate(order, 1):
        lines.append(f'{i}. `{kind}`')
    deferred = [k for k in kinds if k not in order]
    lines += [
        '',
        'Deferred (never auto-selected): ' + ', '.join(f'`{k}`' for k in deferred) + '.',
        'An explicit backend preference that cannot be satisfied is a rejection, never a',
        'silent switch. Source: `crates/ls-core/src/domain/backend.rs` (`BackendKind`,',
        '`AUTO_ORDER`).',
        '',
        '## Host profile tiers',
        '',
        f"Host profiles (`specs/host-profiles.json`, state `{meta.get('state')}`) describe",
        'certification targets; only profiles marked observed carry measurements:',
        '',
        '| Profile | Observed | Intent |',
        '|---|---|---|',
    ]
    for profile in profiles:
        lines.append(f"| `{profile['id']}` | {'yes' if profile.get('observed') else 'no'} "
                     f"| {profile['intent']} |")
    lines += [
        '',
        '## Measured reference host (portable rootless)',
        '',
        f"The one measured host class today is `{observed['id']}` "
        f"(derived tier `{observed['derived_tier']}`; report `{observed['report']}`):",
        '',
        '| Capability area | Observed status |',
        '|---|---|',
    ]
    for name, status in sorted(observed['capabilities_summary'].items()):
        lines.append(f'| `{name}` | {status} |')
    lines += [
        '',
        'Claims this host class must never make:',
        '',
    ]
    for claim in observed['hard_claims_forbidden']:
        lines.append(f'- {claim}')
    lines.append('')
    return '\n'.join(lines)


def main(argv):
    if [a for a in argv if a != '--check']:
        print(__doc__, file=sys.stderr)
        return 2
    data = {'contracts': parse_contracts(), 'backend': parse_backend_rs(),
            'profiles': parse_profiles()}
    text = render(data)
    dims = data['contracts'][0]
    if '--check' not in argv:
        OUTPUT.write_text(text, encoding='utf-8')
        print(f'wrote {OUTPUT.relative_to(ROOT)}: {len(dims)} requirement dimensions, '
              f'{len(data["profiles"][1])} host profiles')
        return 0
    if not OUTPUT.is_file():
        print(f'{OUTPUT.relative_to(ROOT)} missing; run: python3 tools/gen_capability_matrix.py')
        return 1
    current = OUTPUT.read_text(encoding='utf-8')
    if current != text:
        print(f'DRIFT: {OUTPUT.relative_to(ROOT)} differs from regenerated content; '
              'run: python3 tools/gen_capability_matrix.py')
        diff = difflib.unified_diff(current.splitlines(), text.splitlines(),
                                    str(OUTPUT.relative_to(ROOT)), 'regenerated', lineterm='')
        print('\n'.join(list(diff)[:80]))
        return 1
    kinds = data['backend'][0]
    print(f'verified {len(dims)} requirement dimensions (+{len(data["profiles"][1])} host '
          f'profiles, {len(kinds)} backend kinds); {OUTPUT.relative_to(ROOT)} is drift-free')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
